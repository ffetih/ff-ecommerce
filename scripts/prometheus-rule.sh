#!/usr/bin/env bash
# Writes the cluster's PrometheusRule from the compose rules file, so both run the same alerts.
# Run it after editing infra/prometheus/rules/ecommerce.yml and commit both files.
set -euo pipefail
cd "$(dirname "$0")/.."
src=infra/prometheus/rules/ecommerce.yml
out=deploy/infrastructure/monitoring/ecommerce-rules.yaml
{
  echo "# GENERATED by scripts/prometheus-rule.sh from $src: edit that file, then run the script."
  echo "# The Prometheus Operator loads every PrometheusRule into Prometheus; spec is a rules file."
  echo "apiVersion: monitoring.coreos.com/v1"
  echo "kind: PrometheusRule"
  echo "metadata:"
  echo "  name: ecommerce"
  echo "spec:"
  grep -v '^#' "$src" | sed -e '/./,$!d' -e 's/^\(.\)/  \1/'
} > "$out"
echo "wrote $out"
